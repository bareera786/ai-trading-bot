    @staticmethod
    def resume_strategy(strategy_id):
        """Resume a paused strategy."""
        from app.models import Strategy
        s = Strategy.query.get(strategy_id)
        if not s: return False
        
        s.status = "active"
        # Reset health checks
        s.consecutive_losses = 0 
        db.session.commit()
        
        try:
             user_id = current_user.id if current_user and current_user.is_authenticated else "system"
             AuditService.log_event(user_id, "strategy.resume", f"Resumed {s.name}")
        except: pass
        
        return True

    @staticmethod
    def deactivate_model(model_id):
        """Force deactivate an active model (Stop Trading)."""
        target = MLModel.query.get(model_id)
        if not target: return False, "Model not found"
        
        if target.status != "active":
            return False, "Model is not active"
            
        target.status = "archived"
        db.session.commit()
        
        # Audit Log
        try:
            user_id = current_user.id if current_user and current_user.is_authenticated else "system"
            AuditService.log_event(user_id, "brain.model.deactivate", f"Deactivated {target.version} ({target.symbol})")
        except: pass
        
        return True, "Model deactivated successfully"

    @staticmethod
    def delete_model(model_id):
        """Permanently delete a model and its file."""
        import os
        
        target = MLModel.query.get(model_id)
        if not target: return False, "Model not found"
        
        if target.status == "active":
            return False, "Cannot delete an ACTIVE model. Activate another model first."
            
        file_path = target.file_path
        
        # Delete from DB
        try:
            db.session.delete(target)
            db.session.commit()
        except Exception as e:
            db.session.rollback()
            return False, f"DB Error: {e}"
            
        # Delete file
        if file_path and os.path.exists(file_path):
            try:
                os.remove(file_path)
            except Exception as e:
                # Log but don't fail, as DB is already cleaned
                logger.warning(f"Failed to delete model file {file_path}: {e}")
                
        # Audit Log
        try:
            user_id = current_user.id if current_user and current_user.is_authenticated else "system"
            AuditService.log_event(user_id, "brain.model.delete", f"Deleted model {model_id}")
        except: pass
        
        return True, "Model deleted permanently"
